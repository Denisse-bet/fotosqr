-- FotosQR: configuración inicial de base de datos y almacenamiento.
-- Ejecuta todo este archivo en Supabase > SQL Editor > New query.
-- Crea un bucket PRIVADO y permite cargas anónimas limitadas al bucket.

create table if not exists public.fotos (
  id bigint generated by default as identity primary key,
  evento text not null check (char_length(evento) between 1 and 50),
  archivo text not null unique,
  nombre_original text not null,
  tipo_mime text not null check (tipo_mime in ('image/jpeg','image/png','image/webp')),
  tamano_bytes bigint not null check (tamano_bytes > 0 and tamano_bytes <= 10485760),
  creado_en timestamptz not null default now()
);

alter table public.fotos enable row level security;

-- Los visitantes solo pueden insertar metadatos; no pueden leer ni borrar la tabla.
drop policy if exists "FotosQR visitantes pueden registrar fotos" on public.fotos;
create policy "FotosQR visitantes pueden registrar fotos"
on public.fotos for insert to anon
with check (
  char_length(evento) between 1 and 50
  and tipo_mime in ('image/jpeg','image/png','image/webp')
  and tamano_bytes > 0 and tamano_bytes <= 10485760
  and archivo like evento || '/%'
);

-- Crear bucket privado (10 MB por archivo). Es seguro ejecutar si ya existe.
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('fotos-eventos', 'fotos-eventos', false, 10485760, array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set
  public = false,
  file_size_limit = 10485760,
  allowed_mime_types = array['image/jpeg','image/png','image/webp'];

-- Los visitantes pueden subir, pero no listar, descargar ni eliminar archivos.
drop policy if exists "FotosQR permitir carga anonima" on storage.objects;
create policy "FotosQR permitir carga anonima"
on storage.objects for insert to anon
with check (
  bucket_id = 'fotos-eventos'
  and (storage.foldername(name))[1] ~ '^[A-Za-z0-9_-]{1,50}$'
);
